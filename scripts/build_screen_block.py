"""SCREEN — where each covered name stops in the selection funnel, and why.

WHAT THIS IS. The funnel is a chain of gates ordered so the decisions with a
track record run before the ones without: inputs, size cap, the fundamental gap,
the momentum veto, three-lens agreement. This block records, per name, the state
each gate reads and the FIRST gate that stops it, so the screener can show the
chain rather than a single ranked column.

EVERY THRESHOLD IN IT IS INHERITED, NONE IS MINTED. The 10% gap trigger is
[R-GAP-01]'s own, both-sided since 02-09-2026. The momentum dead zone 0.25 and
clip 2.5 are the engine's signal socket. The record-strength cuts 22 and 40 are
[R-CAL-02]'s, derived there from power and from the book's own window counts. A
new number chosen here would be a free parameter with no evidence behind it,
which the promotion rule forbids.

THERE IS DELIBERATELY NO STALENESS CUTOFF. How old a library or a price is gets
REPORTED as a date and never decides anything: staleness is a data-supply fact, a
stale library still yields a coherent read, and a rule carrying a threshold
schedules its own staleness. Gate 1 asks only whether the inputs EXIST.

NOT A RATING AND NOT A RECOMMENDATION. It records what the published numbers say
about each name against the rules already written down; the gap lens has no
graded record, which the block states in its own field rather than leaving to the
reader to remember.

GENERATED, NEVER HAND-EDITED — re-run in the same pass as any price supply,
refit, roll-forward or study re-issue. scripts/check_screen_block.py holds it to
what these readers produce now.
"""
